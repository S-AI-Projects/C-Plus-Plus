/**
 * @brief Self-test implementations
 * @returns void
 */
static void test() {
    // ---------------------------------------------------------
    // Deterministic repeatability and input isolation tests for generate_samples
    // ---------------------------------------------------------
    math::monte_carlo::Function uniform_pdf = [](double&) { return 1.0; };

    // Smallest valid input fixture (num_samples = 1, discard = 0, start_point = 0.0, seed = 42)
    // Precondition established at line 75 (num_samples >= 1) and line 77 (pdf(start_point) > 0)
    std::vector<double> small1 = math::monte_carlo::generate_samples(0.0, uniform_pdf, 1, 0, 42);
    std::vector<double> small2 = math::monte_carlo::generate_samples(0.0, uniform_pdf, 1, 0, 42);
    assert(small1.size() == 1);
    assert(small2.size() == 1);
    assert(small1 == small2);

    // Ordinary input fixture (num_samples = 5, discard = 10, start_point = 0.5, seed = 12345)
    // Precondition established at line 75 (num_samples = 5) and line 84 (seed >= 0)
    std::vector<double> ord1 = math::monte_carlo::generate_samples(0.5, uniform_pdf, 5, 10, 12345);
    std::vector<double> ord2 = math::monte_carlo::generate_samples(0.5, uniform_pdf, 5, 10, 12345);
    assert(ord1.size() == 5);
    assert(ord2.size() == 5);
    assert(ord1 == ord2);

    // Input isolation test: run an intermediate call with different parameters
    std::vector<double> intermediate = math::monte_carlo::generate_samples(1.0, uniform_pdf, 3, 2, 999);
    assert(intermediate.size() == 3);

    // Re-run the ordinary input and verify identical output is preserved
    std::vector<double> ord3 = math::monte_carlo::generate_samples(0.5, uniform_pdf, 5, 10, 12345);
    assert(ord3 == ord1);

    std::cout << "All generate_samples deterministic tests passed successfully!" << std::endl;

    // ---------------------------------------------------------
    // Original integration self-tests
    // ---------------------------------------------------------
    std::cout << "Disclaimer: Because this is a randomized algorithm,"
              << std::endl;
    std::cout
        << "it may happen that singular samples deviate from the true result."
        << std::endl
        << std::endl;

    math::monte_carlo::Function f;
    math::monte_carlo::Function pdf;
    double integral = 0;
    double lower_bound = 0, upper_bound = 0;

    /* \int_{-2}^{2} -x^2 + 4 dx */
    f = [&](double& x) { return -x * x + 4.0; };

    lower_bound = -2.0;
    upper_bound = 2.0;
    pdf = [&](double& x) {
        if (x >= lower_bound && x <= -1.0) {
            return 0.1;
        }
        if (x <= upper_bound && x >= 1.0) {
            return 0.1;
        }
        if (x > -1.0 && x < 1.0) {
            return 0.4;
        }
        return 0.0;
    };

    integral = math::monte_carlo::integral_monte_carlo(
        (upper_bound - lower_bound) / 2.0, f, pdf, 10000);

    std::cout << "This number should be close to 10.666666: " << integral
              << std::endl;

    /* \int_{0}^{1} e^x dx */
    f = [&](double& x) { return std::exp(x); };

    lower_bound = 0.0;
    upper_bound = 1.0;
    pdf = [&](double& x) {
        if (x >= lower_bound && x <= 0.2) {
            return 0.1;
        }
        if (x > 0.2 && x <= 0.4) {
            return 0.4;
        }
        if (x > 0.4 && x < upper_bound) {
            return 1.5;
        }
        return 0.0;
    };

    integral = math::monte_carlo::integral_monte_carlo(
        (upper_bound - lower_bound) / 2.0, f, pdf, 10000);

    std::cout << "This number should be close to 1.7182818: " << integral
              << std::endl;
}

/**
 * @brief Main function
 * @returns 0 on exit
 */
int main() {
    test();  // run self-test implementations
    return 0;
}
